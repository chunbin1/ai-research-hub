// packages/server/src/services/ragConfig.ts
//
// 检索策略配置。全部可通过环境变量覆盖,无需改代码即可调参。
//
// ## 为什么去掉了距离阈值
//
// 曾经的策略是「粗筛候选 + cosine 距离阈值精筛 + 动态 k」。实测证明这个
// 判据不成立:阈值筛掉多少块,取决于**提问方式**,而不是内容相关性。
//
// 同一篇文档(60 块)对四种问法的距离分布:
//
//   query                      最近     中位     最远    ≤0.7 的块数
//   毛利率                     0.5065  0.7385  0.8319     9 / 60
//   毛利率是多少               0.4787  0.7384  0.8276    10 / 60
//   各环节的毛利率区间是多少     0.4716  0.6764  0.7640    47 / 60
//   火箭发射的毛利率           0.4899  0.6056  0.7006    59 / 60
//
// 查询越长越贴近文档主题,整个分布越向查询平移(中位数 0.7385 → 0.6056),
// 固定的 0.7 只是被分布滑过去。同一个块换个问法,距离浮动 0.18,内容一字未改。
//
// 也就是说 cosine 距离在**同一查询内**可比(排序有意义),**跨查询不可比**
// (绝对值没意义),而固定阈值恰恰要求后者。所以:
//   - 选块改为纯名次(RRF 融合后取前 maxK)
//   - 拒答另做。唯一跨查询稳定的信号是首名距离(实测稳定在 0.47~0.51),
//     但定多少需要评测集校准,不在本次范围

function numEnv(key: string, def: number, allowZero = false): number {
  const raw = process.env[key]
  if (raw === undefined || raw === '') return def
  const v = Number(raw)
  if (!Number.isFinite(v) || v < 0) return def
  if (v === 0 && !allowZero) return def
  return v
}

export const RAG = {
  /**
   * 最终交给模型的块数。
   *
   * 曾经是 10,为的是兜住「关键块常排到 6~9 位」—— 用更大的窗口掩盖排序不准,
   * 代价是噪音:实测 citationCoverage 平均 0.155,即塞进去的上下文约 85%
   * 模型没碰。混合检索把正确块顶到前列后,多出来的块只剩成本和干扰。
   */
  maxK: numEnv('RAG_MAX_K', 5),

  /** 每一路在融合前各自召回多少条。融合会去重,所以实际候选数小于两倍。 */
  poolSize: numEnv('RAG_POOL_SIZE', 20),

  /**
   * RRF 的 k:压平头部名次差距。k 小则「某一路的第 1 名」权重极高,
   * k 大则「两路都中游」更容易胜出。工程上从 60 起调。
   */
  rrfK: numEnv('RAG_RRF_K', 60),
}
